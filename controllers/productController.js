const getProducts = async (req, res, next) => {
  try {
    const result = await productService.getProducts(req.query);
    res.status(200).json({
      success: true,
      total: result.total,
      page: result.page,
      totalPages: result.totalPages,
      limit: result.limit,
      data: result.products,
    });
  } catch (error) {
    next(error);
  }
};

